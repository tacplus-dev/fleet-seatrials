# The test IdP's apply (#27), the deploy pipeline's test-idp job: Keycloak in
# the namespace test-idp of the `tacplus` cluster (test-idp/keycloak.yaml),
# its realms (test-idp/realms/), and the DNS record of idp.test.tacplus.dev.
# Run where ci_gcp and ci_kube have put gcloud and kubectl in place as
# test-idp-deploy, which may touch nothing outside that namespace and that
# record (test-idp/rbac.yaml, docs/deploy-pipeline.md).
#
#   test-idp/apply.sh
#
# The secrets: every password and client secret is derived from two seeds
# (test-idp/testidp.py), protected and masked variables of the GitLab project:
#
#   TEST_IDP_SEED          scopes test-idp and seatrials*: the users' passwords,
#                          the admin's (the functional suite, deploy/e2e.yaml,
#                          signs the users in)
#   TEST_IDP_CLIENT_SEED   scopes test-idp and seatrials*: the tacplus-dev
#                          clients' secrets (deploy/signin-secrets.sh reads it)
#
# When one is not set, this job generates it and stores it in the project with
# TEST_IDP_GITLAB_TOKEN (scope test-idp, a project access token with the
# Maintainer role and api scope), so no person ever sees it. That token can
# read every variable of the project, so the hub sets it for the first run
# only and revokes it once the seeds are stored. Nothing here prints a secret,
# and none is on a command line or in an artifact.
set -euo pipefail
here=$(cd "$(dirname "$0")" && pwd)
ns=test-idp
host=idp.test.tacplus.dev
zone=${DNS_ZONE:-tacplus-dev}
port=${ADMIN_PORT:-18080}
[ $# -eq 0 ] || { echo "usage: $0 (no arguments; see the header)" >&2; exit 2; }
ctx=$(kubectl config current-context)
case "$ctx" in *_tacplus) ;; *) echo "kube context is $ctx, not the tacplus cluster" >&2; exit 1 ;; esac

tmp=$(mktemp -d)
pf=""
cleanup() { [ -z "$pf" ] || kill "$pf" 2>/dev/null || true; rm -rf "$tmp"; }
trap cleanup EXIT
umask 077

# gitlab_variable KEY SCOPE FILE: stores FILE's content as a protected, masked
# and hidden variable of this project.
gitlab_variable() {
  : "${TEST_IDP_GITLAB_TOKEN:?$1 is not set and TEST_IDP_GITLAB_TOKEN is not either: the hub sets one of them once (docs/deploy-pipeline.md)}"
  printf 'PRIVATE-TOKEN: %s\n' "$TEST_IDP_GITLAB_TOKEN" > "$tmp/gitlab-header"
  local status
  status=$(curl -sS -o "$tmp/gitlab-answer" -w '%{http_code}' -H @"$tmp/gitlab-header" \
    --data-urlencode "key=$1" --data-urlencode "value@$3" --data-urlencode "environment_scope=$2" \
    -d protected=true -d masked_and_hidden=true -d masked=true -d raw=true \
    --data-urlencode "description=test IdP seed (#27), generated by the test-idp job; test-idp/README.md" \
    "${CI_API_V4_URL:?}/projects/${CI_PROJECT_ID:?}/variables")
  rm -f "$tmp/gitlab-header"
  [ "$status" = 201 ] || { echo "storing $1 (scope $2) in the project: HTTP $status" >&2; exit 1; }
  echo "seeds: $1 generated and stored (scope $2)"
}
ensure_seed() { # NAME SCOPE...
  local name=$1; shift
  [ -z "${!name:-}" ] || return 0
  python3 "$here/testidp.py" new-seed > "$tmp/seed"
  local scope; for scope in "$@"; do gitlab_variable "$name" "$scope" "$tmp/seed"; done
  export "$name=$(cat "$tmp/seed")"
  rm -f "$tmp/seed"
}
ensure_seed TEST_IDP_SEED test-idp 'seatrials*'
ensure_seed TEST_IDP_CLIENT_SEED test-idp 'seatrials*'

mkdir "$tmp/realms"
for f in "$here"/realms/*.yaml; do yq -o=json '.' "$f" > "$tmp/realms/$(basename "$f" .yaml).json"; done

# Keycloak: its admin credential first (read on its first start only), then the rest.
printf admin > "$tmp/admin-user"
python3 "$here/testidp.py" secret admin > "$tmp/admin-password"
kubectl -n "$ns" create secret generic keycloak-admin --from-file=username="$tmp/admin-user" \
  --from-file=password="$tmp/admin-password" --dry-run=client -o yaml | kubectl apply -f - >/dev/null
rm -f "$tmp/admin-password"
kubectl apply -f "$here/keycloak.yaml"
kubectl -n "$ns" rollout status statefulset/keycloak --timeout=600s

# The realms, through the admin API on a port-forward: it is not on the internet.
kubectl -n "$ns" port-forward pod/keycloak-0 "$port:8080" > "$tmp/port-forward.log" 2>&1 &
pf=$!
for _ in $(seq 30); do curl -fsS -o /dev/null "http://127.0.0.1:$port/realms/master" 2>/dev/null && break; sleep 2; done
python3 "$here/testidp.py" sync "http://127.0.0.1:$port" "$tmp"/realms/*.json

# The DNS record: the Ingress's address, once the load balancer has one.
ip=""
for _ in $(seq 60); do
  ip=$(kubectl -n "$ns" get ingress keycloak -o jsonpath='{.status.loadBalancer.ingress[0].ip}')
  [ -z "$ip" ] || break; sleep 10
done
[ -n "$ip" ] || { echo "the Ingress keycloak has no address after 10 minutes" >&2; exit 1; }
have=$(gcloud dns record-sets describe "$host." --type A --zone "$zone" --format='value(rrdatas[0])' 2>/dev/null || true)
if [ "$have" = "$ip" ]; then
  echo "dns: $host A $ip"
elif [ -z "$have" ]; then
  gcloud dns record-sets create "$host." --type A --ttl 300 --rrdatas "$ip" --zone "$zone" >/dev/null
  echo "dns: $host A $ip (created)"
else
  gcloud dns record-sets update "$host." --type A --ttl 300 --rrdatas "$ip" --zone "$zone" >/dev/null
  echo "dns: $host A $ip (was $have)"
fi

# Where the public side is: a new certificate takes up to an hour after DNS.
cert=$(kubectl -n "$ns" get managedcertificate test-idp -o jsonpath='{.status.certificateStatus}' 2>/dev/null || true)
echo "certificate: ${cert:-not provisioned yet}"
for r in "$tmp"/realms/*.json; do
  realm=$(basename "$r" .json)
  if curl -fsS -m 10 -o /dev/null "https://$host/realms/$realm/.well-known/openid-configuration" 2>/dev/null; then
    echo "public: https://$host/realms/$realm answers"
  else
    echo "public: https://$host/realms/$realm does not answer yet (certificate ${cert:-pending}; the test-idp-signin job checks it)"
  fi
done
